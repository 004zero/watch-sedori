const WORKING_RE = /動作(品|確認済|良好|します|しています|OK|ok)|稼働(品|中|確認)|正常(に)?動作|問題なく動/;

function toHalf(s) { return String(s || '').replace(/[Ａ-Ｚａ-ｚ０-９]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0)); }

// 出品文 + ムーブメント → 復活確率（0〜100）・根拠・追加コスト・売値補正
function judge(text, mv) {
  const t = toHalf(text);
  let score = MV[mv][1], extra = 0, saleMul = 1; const reasons = [];
  for (const [re, fn, label, cost, mul] of RULES) {
    const m = t.match(re); if (!m) continue;
    const d = fn(mv, m); if (d === 0 && !cost && !mul) { reasons.push({ d: 0, label }); continue; }
    score += d; if (cost) extra += cost; if (mul) saleMul *= mul; reasons.push({ d, label });
  }
  score = Math.max(0, Math.min(100, score));
  return { score, p: score / 100, extra, saleMul, reasons, working: WORKING_RE.test(t) };
}

function normalize(s) { return toHalf(s).toLowerCase().replace(/[-‐－–—_\s　]/g, ''); }

// 文章からモデルを推定（上位5件）。型番トークンを重く評価
const _TOK = new Map();
function modelTokens(it) {
  if (_TOK.has(it)) return _TOK.get(it);
  const toks = new Set((it.name + ' ' + it.kw + ' ' + it.kj + ' ' + it.brand).split(/[\/／（）()・,、。\s　×]+/).map(normalize).filter(x => x.length >= 3 || (x.length === 2 && /\d/.test(x))));
  _TOK.set(it, toks); return toks;
}
function detectModel(text) {
  const t = normalize(text); const out = [];
  for (const it of ITEMS) {
    let sc = 0; const hit = [];
    for (const tok of modelTokens(it)) { if (t.includes(tok)) { sc += (/\d/.test(tok) ? 3 : 1) * Math.min(tok.length, 8) / 4; hit.push(tok); } }
    if (sc >= 2) out.push({ it, sc, hit });
  }
  return out.sort((a, b) => b.sc - a.sc).slice(0, 5);
}

// ---------- 手取り・期待値（純粋関数） ----------
// 手取り = 売値 × (1 − 手数料%) − 送料 − 梱包
function calcNet(gross, feePct, ship, pack) { return gross * (1 - feePct / 100) - ship - pack; }

// ジャンク期待値。p=復活確率, buy=仕入総額(送料込), cheap=安い処置費, big=本格修理費,
// bestNet=復活時の最良手取り, junkNet=ジャンクのまま再販した手取り, tgtPct/tgtMin=目標利益
function evalJunk({ p, buy, cheap, big, bestNet, junkNet, tgtPct, tgtMin }) {
  const okP = bestNet - buy - cheap;
  const repairP = bestNet - buy - cheap - big, resellP = junkNet - buy - cheap;
  const failP = Math.max(repairP, resellP);
  const ev = p * okP + (1 - p) * failP;
  const target = Math.max(tgtMin, bestNet * tgtPct / 100);
  return { okP, failP, repairP, resellP, ev, target, maxBuy: ev + buy - target, failMode: repairP >= resellP ? 'repair' : 'resell' };
}

// 判定ラベル
function verdictOf({ score, price, ship, J, hasModel }) {
  if (!hasModel) return { v: 'モデル不明', cls: 'wn' };
  if (score < 25) return { v: '見送り', cls: 'ng', why: '電池交換では直らない可能性が高い文言があります。' };
  if (price + ship <= J.maxBuy) return { v: '買い', cls: 'ok', why: `送料込み ${Math.round(J.maxBuy).toLocaleString()}円 までなら目標利益を確保できます。` };
  if (J.ev > 0) return { v: '値下げ待ち', cls: 'wn', why: `利益は出ますが目標に届きません。送料込み ${Math.round(J.maxBuy).toLocaleString()}円 以下なら買い。` };
  return { v: '見送り', cls: 'ng', why: 'この価格だと期待利益がマイナスです。' };
}
